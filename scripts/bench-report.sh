#!/usr/bin/env bash
# Renders summary.md for a benchmark run directory written by scripts/bench.sh.
#
#   scripts/bench-report.sh bench/results/<run> > bench/results/<run>/summary.md
set -euo pipefail
DIR=${1:?usage: bench-report.sh RESULTS_DIR}
ENV="$DIR/env.json"

med='def median: sort | if length == 0 then null elif length % 2 == 1 then .[length/2|floor] else (.[length/2-1] + .[length/2]) / 2 end;'
r0() { awk '{printf "%.0f", $1}'; }
r1() { awk '{printf "%.1f", $1}'; }

echo "# Benchmark results: $(jq -r .run "$ENV")"
echo
echo "Generated by \`scripts/bench-report.sh\` from the raw files in this directory."
echo
echo "## Environment"
echo
jq -r '"- Commit: `\(.commit)`",
       "- CPU: \(.cpu), \(.cpus) vCPUs; memory \(.memory); kernel \(.kernel)",
       "- Docker \(.docker), \(.go); image \(.image)",
       "- Setup: \(.setup)",
       "- Payload \(.params.payload_bytes) bytes; closed-loop runs use \(.params.producers) producers and \(.params.workers) workers"' "$ENV"
echo
echo "Submit-to-ack latency runs from the start of a Submit call to the end of the"
echo "worker's successful Ack for that job: submit commit, time queued, claim commit,"
echo "worker poll delay and ack commit. Every write is committed by a Raft quorum and"
echo "fsynced before it is acknowledged."
echo

echo "## Throughput by cluster size"
echo
echo "Closed loop for $(jq -r .params.duration "$ENV") per run, $(jq -r .params.reps "$ENV") runs per size; median with [min-max] across runs."
echo
echo "| Nodes | Completed jobs/s | Submit-to-ack p50 (ms) | p95 (ms) | p99 (ms) | Jobs lost |"
echo "| --- | --- | --- | --- | --- | --- |"
for n in 1 3 5; do
  files=("$DIR"/throughput/n$n-r*/result.json)
  [[ -e "${files[0]}" ]] || continue
  rates=$(jq -s "$med [.[].ack_rate_per_sec] | {m: median, lo: min, hi: max}" "${files[@]}")
  p50=$(jq -s "$med [.[].submit_to_ack_latency_ms.p50] | median" "${files[@]}" | r1)
  p95=$(jq -s "$med [.[].submit_to_ack_latency_ms.p95] | median" "${files[@]}" | r1)
  p99=$(jq -s "$med [.[].submit_to_ack_latency_ms.p99] | median" "${files[@]}" | r1)
  lost=$(jq -s '[.[].jobs_lost] | add' "${files[@]}")
  submitted=$(jq -s '[.[].submits_acknowledged] | add' "${files[@]}")
  echo "| $n | $(jq .m <<<"$rates" | r0) [$(jq .lo <<<"$rates" | r0)-$(jq .hi <<<"$rates" | r0)] | $p50 | $p95 | $p99 | $lost of $submitted |"
done
echo

if [[ -f "$DIR/latency/result.json" ]]; then
  echo "## Latency at a fixed rate (3 nodes)"
  echo
  echo "| Target submits/s | Achieved jobs/s | p50 (ms) | p95 (ms) | p99 (ms) | max (ms) | Submit p50 / p99 (ms) | Jobs lost |"
  echo "| --- | --- | --- | --- | --- | --- | --- | --- |"
  jq -r '"| \(.config.Rate) | \(.ack_rate_per_sec | floor) | \(.submit_to_ack_latency_ms.p50 * 10 | round / 10) | \(.submit_to_ack_latency_ms.p95 * 10 | round / 10) | \(.submit_to_ack_latency_ms.p99 * 10 | round / 10) | \(.submit_to_ack_latency_ms.max * 10 | round / 10) | \(.submit_latency_ms.p50 * 10 | round / 10) / \(.submit_latency_ms.p99 * 10 | round / 10) | \(.jobs_lost) of \(.submits_acknowledged) |"' "$DIR/latency/result.json"
  echo
fi

if [[ -f "$DIR/chaos/result.json" ]]; then
  K="$DIR/chaos/kills.jsonl"
  echo "## Chaos: leader killed repeatedly under load (3 nodes)"
  echo
  echo "\`docker kill\` (SIGKILL) of the current leader every $(jq -r .params.kill_gap "$ENV") while producers submit at"
  echo "$(jq -r .params.chaos_rate "$ENV")/s; the killed node is restarted and rejoins before the next kill."
  echo "Failover time is measured by \`quorumq-load probe\` from the kill until a Submit is"
  echo "acknowledged again (10 ms retry interval)."
  echo
  jq -rs --slurpfile r "$DIR/chaos/result.json" "$med"'
    "| Leader kills | Failover median (ms) | Failover min-max (ms) | Acknowledged submits | Completed | Jobs lost | Duplicate deliveries |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    "| \(length) | \([.[].failover_ms] | median | round) | \([.[].failover_ms] | min | round)-\([.[].failover_ms] | max | round) | \($r[0].submits_acknowledged) | \($r[0].jobs_completed) | \($r[0].jobs_lost) | \($r[0].duplicate_completions) |"' "$K"
  echo
  echo "Per kill:"
  echo
  echo "| Kill | Killed leader | New leader | Failover (ms) |"
  echo "| --- | --- | --- | --- |"
  jq -r '"| \(.kill) | \(.killed) | \(.new_leader) | \(.failover_ms | round) |"' "$K"
  echo
  echo "Jobs lost = acknowledged submits (\`chaos/submitted.csv\`) with no completed job"
  echo "(\`chaos/completed.csv\`). Duplicates are expected under at-least-once delivery: a job"
  echo "whose claim or ack response was lost in a failover is redelivered after its 5 s lease,"
  echo "and a submit retried after a leader crash may enqueue a second copy."
fi
