#!/usr/bin/env bash
# Runs an N-node quorumq cluster in Docker for benchmarks and chaos tests.
#
#   scripts/cluster.sh up N     # start N nodes (1-5): gRPC on localhost:7071.., HTTP on :8081..
#   scripts/cluster.sh down     # stop and delete the cluster and its volumes
#   scripts/cluster.sh leader   # print the leader's node name (n1..nN)
#   scripts/cluster.sh addrs    # print the client address list
#
# The image quorumq:dev must exist (docker build -t quorumq:dev .).
set -euo pipefail

cd "$(dirname "$0")/.."
PROJECT=quorumq-bench
STATE_DIR=.bench
COMPOSE_FILE="$STATE_DIR/compose.yml"
compose() { docker compose -p "$PROJECT" -f "$COMPOSE_FILE" "$@"; }

size() { cat "$STATE_DIR/size" 2>/dev/null || echo 0; }

addrs() {
  local n out=()
  n=$(size)
  for ((i = 1; i <= n; i++)); do out+=("localhost:707$i"); done
  (IFS=,; echo "${out[*]}")
}

status() { curl -sf --max-time 1 "localhost:808$1/status" 2>/dev/null || echo '{}'; }

leader() {
  local n
  n=$(size)
  for ((i = 1; i <= n; i++)); do
    if [[ "$(status "$i" | jq -r .state)" == "Leader" ]]; then echo "n$i"; return 0; fi
  done
  return 1
}

up() {
  local n=$1
  if (( n < 1 || n > 5 )); then echo "cluster size must be 1-5" >&2; exit 1; fi
  mkdir -p "$STATE_DIR"
  local peers=() i
  for ((i = 1; i <= n; i++)); do peers+=("n$i=n$i:7000/localhost:707$i"); done
  local peer_list
  peer_list=$(IFS=,; echo "${peers[*]}")

  {
    echo "# Generated by scripts/cluster.sh; do not edit."
    echo "name: $PROJECT"
    echo "services:"
    for ((i = 1; i <= n; i++)); do
      cat <<EOF
  n$i:
    image: quorumq:dev
    hostname: n$i
    command: ["-node-id=n$i", "-addr=0.0.0.0:7070", "-raft-addr=0.0.0.0:7000",
              "-http-addr=0.0.0.0:8080", "-data-dir=/data", "-peers=$peer_list"]
    ports: ["707$i:7070", "808$i:8080"]
    volumes: ["n$i-data:/data"]
EOF
    done
    echo "volumes:"
    for ((i = 1; i <= n; i++)); do echo "  n$i-data:"; done
  } > "$COMPOSE_FILE"
  echo "$n" > "$STATE_DIR/size"

  compose up -d --quiet-pull >/dev/null 2>&1
  for _ in $(seq 1 150); do
    local ready=0
    for ((i = 1; i <= n; i++)); do
      curl -sf --max-time 1 "localhost:808$i/readyz" >/dev/null 2>&1 && ready=$((ready + 1))
    done
    if (( ready == n )); then echo "cluster of $n ready; leader $(leader)"; return 0; fi
    sleep 0.2
  done
  echo "cluster did not become ready" >&2
  compose logs --tail 20 >&2
  exit 1
}

down() {
  [[ -f "$COMPOSE_FILE" ]] && compose down -v --remove-orphans >/dev/null 2>&1 || true
  rm -f "$STATE_DIR/size"
}

case "${1:-}" in
  up) up "${2:?usage: cluster.sh up N}" ;;
  down) down ;;
  leader) leader ;;
  addrs) addrs ;;
  status) for ((i = 1; i <= $(size); i++)); do status "$i" | jq -c '{node_id, state, term, commit_index, fsm_applied_index}'; done ;;
  *) echo "usage: cluster.sh up N | down | leader | addrs | status" >&2; exit 1 ;;
esac
